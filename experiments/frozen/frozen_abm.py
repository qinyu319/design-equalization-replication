# ── Stable hashing ────────────────────────────────────────────────────────────

def stable_hash_int(s: str, modulo: int = 10000) -> int:
    """Deterministic, process-independent hash (Python's built-in hash() is salted)."""
    h = hashlib.sha256(s.encode("utf-8")).hexdigest()
    return int(h[:12], 16) % modulo


# ── CLI ───────────────────────────────────────────────────────────────────────

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--config", required=True, help="Path to YAML config file")
    p.add_argument("--seed_manifest", default=None,
                   help="Optional path to a seed_manifest.csv. If given, seeds are replayed "
                        "from the manifest (exact reproduction of bundled outputs) instead of "
                        "being generated by the stable SHA-256 seed generator.")
    return p.parse_args()


def load_seed_manifest(path: str) -> dict:
    """Load a seed manifest into a lookup keyed by cell identity.

    Key: (topology, message_condition, inoculation, seeding_regime, replication)
    Value: dict of seed_net/seed_attr/seed_sim/seed_inoc.
    Accepts both the unified field names and the legacy names (condition/regime/rep).
    """
    lookup = {}
    with open(path, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            cond = r.get("message_condition", r.get("condition"))
            regime = r.get("seeding_regime", r.get("regime"))
            rep = int(r.get("replication", r.get("rep")))
            key = (r["topology"], cond, r["inoculation"], regime, rep)
            seed_sim = r.get("seed_sim")
            lookup[key] = {
                "master_seed": int(r["master_seed"]) if r.get("master_seed") else None,
                "seed_net": int(r.get("seed_net") or r["network_seed"]),
                "seed_attr": int(r.get("seed_attr") or r["initialization_seed"]),
                "seed_seeding": int(r.get("seed_seeding", r.get("seeding_seed", seed_sim))),
                "seed_sharing": int(r.get("seed_sharing", r.get("sharing_seed", seed_sim))),
                "seed_noise": int(r.get("seed_noise", r.get("noise_seed", seed_sim))),
                "seed_sim": int(seed_sim) if seed_sim else None,
                "seed_inoc": int(r.get("seed_inoc") or r["inoculation_seed"]),
            }
    return lookup


