"""
run_all.py — Config-driven runner for the ABM factorial simulation.

Usage:
    python run_all.py --config configs/main_calibrated.yaml

Implements the full model described in the CCR manuscript:
  - 4 network topologies: BA, ER, WS, SBM
  - N message conditions with configurable delta_m per condition
  - 3 inoculation strategies: none, random, hub
  - 3 seeding regimes: single_shot, burst, continuous (+ dose-matched variant)
  - Opinion update: Eqs. 1–3 from the paper
  - Primary outcomes: mean total shift (Eq. 4), mean signed shift (Eq. 5), conversion rate (Eq. 6)
  - Outputs: raw CSV per run + seed manifest
"""

